// Build the game's codex (lore_entries) from the EverBloom wiki in everbloom-lore/ (the canon).
//
//   node scripts/build-lore.mjs        → rewrites drizzle/migrations/0009_lore_from_wiki.sql
//
// Each page's slug is its frontmatter `slug`, else its filename before "--". Pages that replace an
// older codex entry pin that entry's slug so players keep their discoveries. src/test/lore.test.ts
// fails if the migration is stale or a [[link]] points at a page that doesn't exist.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const LORE_DIR = join(ROOT, "everbloom-lore");
export const OUT = join(ROOT, "drizzle/migrations/0009_lore_from_wiki.sql");
const QUIET_TAGS = new Set(["imported", "game-sync", "stub", "needs-owner", "wardens"]);

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith(".md") ? [join(dir, e.name)] : []);
}

export function parsePage(path, text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const fm = {};
  if (m) for (const line of m[1].split("\n")) {
    const kv = line.match(/^([\w ]+):\s*(.*)$/);
    if (kv) fm[kv[1].trim()] = kv[2].trim();
  }
  const unquote = (v) => (v ?? "").replace(/^"(.*)"$/, "$1");
  const file = path.split("/").pop().replace(/\.md$/, "");
  const tags = (fm.tags ?? "").match(/"([^"]+)"/g)?.map((t) => t.slice(1, -1)) ?? [];
  return {
    path: relative(ROOT, path),
    slug: unquote(fm.slug) || file.split("--")[0],
    title: unquote(fm.title) || file,
    tags,
    body: (m ? m[2] : text).replace(/^---\s*$/gm, "").trim(),
  };
}

export function loadPages(dir = LORE_DIR) {
  return walk(dir).sort().map((p) => parsePage(p, readFileSync(p, "utf8")));
}

/** Wiki markdown → the codex's plain text (it renders with white-space: pre-line). */
export function mdToText(md) {
  return md
    .replace(/\[\[([^\]|]+)\|([^\]]+)\]\]/g, "$2")
    .replace(/\[\[([^\]]+)\]\]/g, "$1")
    .replace(/\b([Tt])he The\b/g, "$1he")                 // wiki writes "the [[The Wilderness]]"
    .replace(/^\|.*\|\n\|[-| ]+\|$/gm, "")              // table header + separator rows
    .replace(/^\|(.*)\|$/gm, (_, row) => "• " + row.split("|").map((c) => c.trim()).filter(Boolean).join(" — "))
    .replace(/^#{1,6}\s*(.*)$/gm, "$1")
    .replace(/^\s*[*-]\s+/gm, "• ")
    .replace(/^\s*>\s?/gm, "")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\*([^*\n]+)\*/g, "$1")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export function summaryOf(md) {
  const para = md.split(/\n\s*\n/).map((p) => p.trim()).find((p) => p && !p.startsWith("#") && !p.startsWith("|"));
  return mdToText(para ?? "").replace(/\s+/g, " ").slice(0, 280);
}

const norm = (s) => s.toLowerCase().replace(/^the\s+/, "").trim();

/** [[links]] whose target is not a page title, slug or filename. */
export function brokenLinks(pages) {
  const known = new Set(pages.flatMap((p) => [norm(p.title), norm(p.slug.replace(/-/g, " "))]));
  const out = [];
  for (const p of pages) for (const m of p.body.matchAll(/\[\[([^\]|]+)/g)) {
    if (!known.has(norm(m[1]))) out.push(`${p.path}: [[${m[1]}]]`);
  }
  return out;
}

const sq = (s) => "'" + String(s).replace(/'/g, "''") + "'";

export function buildSql(pages) {
  const rows = pages.map((p) => {
    const keywords = [...new Set([norm(p.title), p.slug.replace(/-/g, " "), ...p.tags.filter((t) => !QUIET_TAGS.has(t))])];
    return `(${sq(p.slug)}, ${sq(p.title)}, ${sq(p.path)}, ${sq(summaryOf(p.body))}, ${sq(mdToText(p.body))}, ARRAY[${keywords.map(sq).join(", ")}]::text[])`;
  });
  return `-- GENERATED by scripts/build-lore.mjs from everbloom-lore/ (the canon). Do not edit by hand:
-- edit the wiki pages, then run \`node scripts/build-lore.mjs\`.
INSERT INTO public.lore_entries (slug, title, source_url, summary, content, keywords) VALUES
${rows.join(",\n")}
ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, source_url = EXCLUDED.source_url,
  summary = EXCLUDED.summary, content = EXCLUDED.content, keywords = EXCLUDED.keywords, updated_at = now();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const pages = loadPages();
  const dupes = pages.map((p) => p.slug).filter((s, i, a) => a.indexOf(s) !== i);
  if (dupes.length) { console.error("duplicate slugs:", dupes); process.exit(1); }
  const broken = brokenLinks(pages);
  if (broken.length) console.warn(`warning: ${broken.length} broken links\n  ` + broken.join("\n  "));
  writeFileSync(OUT, buildSql(pages));
  console.log(`wrote ${relative(ROOT, OUT)} (${pages.length} entries)`);
}
